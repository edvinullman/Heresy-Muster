import fs from 'node:fs'; import path from 'node:path';
import { GameData } from '../js/data.js'; import { Roster, newRosterRaw } from '../js/engine.js';
import { MANIFEST } from '../js/manifest.js'; import { POINTS_ID } from '../js/config.js';
const dir = process.argv[2]; const data = new GameData(MANIFEST);
const load = (m) => data.addFile(JSON.parse(fs.readFileSync(path.join(dir, m.file), 'utf8')));
const gs = MANIFEST.find(m => m.type === 'gameSystem'); load(gs);
const um = MANIFEST.find(m => m.name.includes('Ultramarines')); for (const m of data.filesNeeded(um.id)) load(m);
const r = new Roster(data, newRosterRaw({ name: 'T', catalogueId: um.id, gameSystemId: gs.id, points: 3000 }));
let foc = r.addForce(r.root, r.childForceChoices(r.root).find(c => c.node.name.startsWith('Crusade')).node);
const F = () => r.allForces.find(x => x.node.name.startsWith('Crusade'));
const P = () => r.allForces.find(x => x.node.name === 'Crusade Primary Detachment');
r.addRoot(F(), r.rootChoices(F()).find(c => c.node.name === 'Allegiance').node);
r.addRoot(F(), r.rootChoices(F()).find(c => c.node.name === 'Rite of War').node);
const rite = r.allSels.find(s => s.node.name === 'Rite of War');
const show = (items, d = 1, maxd=3) => items.forEach(i => { if (i.state.hidden) return; const l = r.limitsOf(i.state); console.log(' '.repeat(d * 2) + `${i.kind} ${i.state.name} [${l.min}-${l.max}] n=${i.count}`); if (i.children && d < maxd) show(i.children, d + 1, maxd); });
show(r.options(rite));
const t0=Date.now();
const add = (name) => { const c = r.rootChoices(P()).find(c => c.node.name === name); if(!c) {console.log('NO', name); return;} const raw = r.addRoot(P(), c.node); return r.selByRaw(raw); };
add('Praetor');
for (let i=0;i<6;i++) add('Tactical Squad');
let ts = r.allSels.find(s => s.node.name === 'Tactical Squad');
const leg = ts.children.find(c => c.node.name === 'Legionary'); r.setNumber(leg, 19);
ts = r.allSels.find(s => s.node.name === 'Tactical Squad');
const prime = r.options(ts).find(i => i.state.name === 'Prime Unit');
r.setOptionCount(ts, prime, 1);
ts = r.allSels.find(s => s.node.name === 'Tactical Squad');
console.log('TS cats', r.selState(ts).categories.map(c => data.categoryName(c)), 'primary', data.categoryName(r.selState(ts).primary));
const pu = ts.children.find(c=>c.node.name==='Prime Unit'); console.log('prime unit opts'); show(r.options(pu));
const pr = r.allSels.find(s => s.node.name === 'Praetor'); console.log('Praetor', r.selTotal(pr, POINTS_ID)); show(r.options(pr),1,2);
console.log('slots', r.slots(P()).filter(s=>!s.state.hidden).map(s => { const l=r.limitsOf(s.state); return `${s.state.name}:${r.sumSel(P(), x=>r.matches(x,s.categoryId), false,false)}/${l.max}`;}).join(' '));
console.log('TOTAL', r.total(), 'ms', Date.now()-t0);
const t1=Date.now(); const v = r.validate(); console.log('validate ms', Date.now()-t1); console.log(v.map(x=>x.level+': '+x.msg).join('\n'));
for (const s of r.slots(P())) { if (!['Prime Troops','Troops'].includes(s.state.name)) continue; for (const c of s.state.constraints) console.log(s.state.name, c.type, c.value, 'count=', r.count({...c, childId: c.owner}, {self:null,parent:P(),force:P()})); }
