// Builds js/rule-index.js: rule name -> [data file, rule id]. Names and ids only, no rule text.
// Run: node tools/build-rule-index.mjs <data-folder>
import fs from 'node:fs'; import path from 'node:path';
import { MANIFEST } from '../js/manifest.js';
import { ruleKey } from '../js/rule-names.js';
const dir = process.argv[2];
const idx = new Map();
const rank = (m, key) => (m.name === 'Special Rules' ? 0 : m.type === 'gameSystem' ? 1 : m.library ? 2 : 3) + (key === 'sharedRules' ? 0 : 0.5);
for (const m of MANIFEST) {
  const root = Object.values(JSON.parse(fs.readFileSync(path.join(dir, m.file), 'utf8')))[0];
  const walk = (o, key) => {
    if (Array.isArray(o)) { o.forEach(x => walk(x, key)); return; }
    if (!o || typeof o !== 'object') return;
    if ((key === 'sharedRules' || key === 'rules') && o.name && o.description) {
      const r = rank(m, key);
      for (const n of [o.name, ...(o.alias || [])]) {
        const k = ruleKey(n), cur = idx.get(k);
        if (!cur || r < cur.r || (r === cur.r && m.size < cur.size)) idx.set(k, { file: m.file, id: o.id, r, size: m.size });
      }
    }
    for (const k in o) if (o[k] && typeof o[k] === 'object') walk(o[k], k);
  };
  walk(root, '');
}
const out = Object.fromEntries([...idx].sort().map(([k, v]) => [k, [v.file, v.id]]));
fs.writeFileSync(new URL('../js/rule-index.js', import.meta.url),
  '// Where each rule is defined in the pinned data: name -> [file, rule id].\n// Generated by tools/build-rule-index.mjs. Names and ids only; text is fetched on demand.\nexport const RULE_INDEX = ' + JSON.stringify(out) + ';\n');
const byFile = {};
for (const v of idx.values()) byFile[v.file] = (byFile[v.file] || 0) + 1;
console.log('rules:', idx.size, byFile);
